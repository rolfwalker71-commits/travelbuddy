/** Liefert Linienzüge (in u/v-Einheiten) für einen Text, Höhe `h`, ab (u0,v0). */
function layout(str, u0, v0, h, opt = {}) {
  const sc = h / 5, adv = (opt.advance || 4.2) * sc;
  const strokes = [];
  const chars = String(str).toUpperCase().split('');
  const total = chars.length * adv - adv * 0.25;
  let u = u0;
  if (opt.align === 'center') u = u0 - total / 2;
  else if (opt.align === 'right') u = u0 - total;
  for (const ch of chars) {
    const g = G[ch] || G[' '];
    for (const s of g) strokes.push(s.map(p => [u + p[0] * sc, v0 + p[1] * sc]));
    u += adv;
  }
  return { strokes, width: total };
}

module.exports = { layout, GLYPHS: G };
